# -*- coding: utf-8 -*-
"""Jackson-compatible JSON serialization.

Migrated from: (no Java source -- replaces Jackson's ObjectMapper defaults)

Why this exists
---------------
The ported controllers return the same objects the Java code returned
(``AjaxResult``, ``TableDataInfo``, domain entities, raw ``List``). Jackson
turned them into JSON with three properties this module reproduces:

1. **Field names** are the Java property names (camelCase), not the Python
   snake_case attribute names. A few acronym names (``gantryCaptureBO``)
   cannot be reconstructed from snake_case, so exact names are read from
   ``app/compat/java_meta.py`` when it exists.
2. **nulls are emitted** (Jackson default ``Include.ALWAYS``), which is why
   ``call-setters-on-nulls: true`` matters on the MyBatis side.
3. **Dates** honour ``@JsonFormat(pattern = ...)``; values without a pattern
   are written as ISO-8601 with milliseconds and an offset, because Spring
   Boot disables ``WRITE_DATES_AS_TIMESTAMPS`` by default.

Timezone
--------
``application.yml`` has no ``spring.jackson.time-zone``, so Jackson's default
(UTC) applies, while the JDBC session reads timestamps in the JVM timezone
(``serverTimezone=Asia/Shanghai`` in the URL). A naive datetime coming from
GaussDB is therefore shifted to UTC before formatting -- that is what the Java
service actually emits, even though it looks surprising. Both zones are
configurable through ``CAR_MONIT_DB_TIMEZONE`` / ``CAR_MONIT_JSON_TIMEZONE``.
"""
from __future__ import annotations

import base64
import dataclasses
import datetime as _dt
import enum
import os
from decimal import Decimal
from typing import Any, Optional
from zoneinfo import ZoneInfo

from app.compat.meta_key import meta_get
from com.ruoyi.common.core.domain.JavaBean import snake_to_camel
from com.ruoyi.common.core.page.TableDataInfo import TableDataInfo

__all__ = ["to_jsonable", "java_pattern_to_strftime", "json_formats_for"]

try:  # generated by tools/gen_java_meta.py; optional at first start
    from app.compat.java_meta import JSON_FORMATS, JAVA_NAMES
except Exception:  # pragma: no cover - generator not run yet
    JSON_FORMATS: dict[str, dict[str, str]] = {}
    JAVA_NAMES: dict[str, dict[str, str]] = {}

_DB_TZ = ZoneInfo(os.environ.get("CAR_MONIT_DB_TIMEZONE", "Asia/Shanghai"))
_JSON_TZ = ZoneInfo(os.environ.get("CAR_MONIT_JSON_TIMEZONE", "UTC"))

# Java SimpleDateFormat tokens, longest first so "yyyy" wins over "yy"
_JAVA_TOKENS = (
    ("yyyy", "%Y"),
    ("yyy", "%Y"),
    ("yy", "%y"),
    ("MMMM", "%B"),
    ("MMM", "%b"),
    ("MM", "%m"),
    ("dd", "%d"),
    ("HH", "%H"),
    ("hh", "%I"),
    ("mm", "%M"),
    ("ss", "%S"),
    ("SSS", "%f"),
    ("a", "%p"),
)


def java_pattern_to_strftime(pattern: str) -> str:
    """``yyyy-MM-dd HH:mm:ss`` -> ``%Y-%m-%d %H:%M:%S``."""
    out: list[str] = []
    index = 0
    length = len(pattern)
    while index < length:
        for token, replacement in _JAVA_TOKENS:
            if pattern.startswith(token, index):
                out.append(replacement)
                index += len(token)
                break
        else:
            char = pattern[index]
            out.append("%%" if char == "%" else char)
            index += 1
    return "".join(out)


def json_formats_for(instance: Any) -> dict[str, str]:
    """``@JsonFormat`` patterns of a domain object, keyed by Python field name."""
    # 元数据表用 Java 全限定类名做键，而模块路径本身就是那个 FQCN，
    # 拼接 module + "." + name 会得到两次类名（见 app/compat/meta_key.py）。
    return meta_get(JSON_FORMATS, type(instance), {})


def _java_names_for(instance: Any) -> dict[str, str]:
    return meta_get(JAVA_NAMES, type(instance), {})


def _format_datetime(value: _dt.datetime, pattern: Optional[str]) -> str:
    if value.tzinfo is None:
        value = value.replace(tzinfo=_DB_TZ)
    value = value.astimezone(_JSON_TZ)
    if pattern:
        text = value.strftime(java_pattern_to_strftime(pattern))
        if "SSS" in pattern:
            # %f is microseconds; Java SSS is milliseconds
            text = text.replace("000000", "000")
        return text
    return value.strftime("%Y-%m-%dT%H:%M:%S.") + f"{value.microsecond // 1000:03d}" + value.strftime("%z")[:3] + ":" + value.strftime("%z")[3:]


def to_jsonable(value: Any) -> Any:
    """Recursively convert a Java-shaped object graph into JSON-ready values."""
    if value is None:
        return None
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, str)):
        return value
    if isinstance(value, float):
        return value
    if isinstance(value, Decimal):
        # Jackson writes BigDecimal as a JSON number
        return float(value)
    if isinstance(value, enum.Enum):
        return value.name
    if isinstance(value, (bytes, bytearray)):
        return base64.b64encode(bytes(value)).decode("ascii")
    if isinstance(value, _dt.datetime):
        return _format_datetime(value, None)
    if isinstance(value, _dt.date):
        return value.isoformat()
    if isinstance(value, _dt.time):
        return value.isoformat()
    if isinstance(value, TableDataInfo):
        # field declaration order of TableDataInfo.java: total, rows, code, msg
        return {
            "total": value.total,
            "rows": to_jsonable(value.rows),
            "code": value.code,
            "msg": value.msg,
        }
    if isinstance(value, dict):
        return {str(key): to_jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [to_jsonable(item) for item in value]
    if dataclasses.is_dataclass(value) and not isinstance(value, type):
        patterns = json_formats_for(value)
        java_names = _java_names_for(value)
        result: dict[str, Any] = {}
        for field_info in dataclasses.fields(value):
            if field_info.name.startswith("_"):
                continue
            key = java_names.get(field_info.name) or snake_to_camel(field_info.name)
            raw = getattr(value, field_info.name, None)
            pattern = patterns.get(field_info.name)
            if pattern and isinstance(raw, _dt.datetime):
                result[key] = _format_datetime(raw, pattern)
            elif pattern and isinstance(raw, _dt.date) and not isinstance(raw, _dt.datetime):
                result[key] = raw.strftime(java_pattern_to_strftime(pattern))
            else:
                result[key] = to_jsonable(raw)
        return result
    # Plain JavaBean-style object (R, Result, PageDomain ...)
    attributes = getattr(value, "__dict__", None)
    if attributes is not None:
        return {
            snake_to_camel(name): to_jsonable(item)
            for name, item in attributes.items()
            if not name.startswith("_")
        }
    return str(value)
