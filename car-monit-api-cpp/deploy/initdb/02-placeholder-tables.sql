-- =============================================================================
-- 本地联调占位 schema（仅用于 docker compose 快速起环境，禁止直接用于生产）
--
-- 来源与依据：
--   * 表名/列名取自 car-monit-api-cpp/src/meta/entities_generated.h（与 Java 实体、
--     MyBatis resultMap 一一对应），保证服务实际 SELECT/INSERT 的列都存在。
--   * 仓库内没有完整的生产 DDL；仅 pro-business-api/src/main/resources/sql/
--     partition_scheme.sql（3 张核心表的设计样例）与 setup_script/sql/
--     10_kafka_message_record.pg.sql（真实 DDL）可用。
--   * 因此除 kafka_message_record 外，其余表在本文件中按“列名对齐、类型近似”生成，
--     没有主键约束以外的索引/分区/约束。生产部署必须替换为数据仓提供的真实 DDL。
--
-- 已知限制：
--   * ods_szdn_service 的 yyrq 是 to_char(business_date,...) 表达式，这里补齐
--     business_date 列，保证该实体的 SELECT 片段可执行。
--   * 除主键列外所有列允许 NULL；数值列按实体类型映射，真实精度/长度需以生产 DDL 为准。
--   * 标识符不加引号：服务端 SQL 未加引号，PostgreSQL 会统一折叠为小写
--     （例如 dataSource -> datasource），保证列名匹配。
-- =============================================================================


